-- Funciones fixture: misma firma/contrato mínimo consumido por el command.
IF OBJECT_ID('dbo.VALIDUNIT', 'FN') IS NOT NULL DROP FUNCTION dbo.VALIDUNIT;
GO
CREATE FUNCTION dbo.VALIDUNIT(@unidad VARCHAR(50))
RETURNS VARCHAR(50)
AS
BEGIN
    RETURN CASE WHEN @unidad IS NULL OR LTRIM(RTRIM(@unidad)) = '' THEN 'SD' ELSE LTRIM(RTRIM(@unidad)) END;
END;
GO

