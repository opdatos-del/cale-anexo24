-- Trigger TEST-ONLY para provocar rollback determinista tras un write previo.
IF OBJECT_ID('dbo.TR_PartidasRollbackTest', 'TR') IS NOT NULL DROP TRIGGER dbo.TR_PartidasRollbackTest;
GO
CREATE TRIGGER dbo.TR_PartidasRollbackTest ON dbo.PARTIDAS AFTER INSERT
AS
BEGIN
    IF EXISTS (SELECT 1 FROM inserted WHERE CLAVE = 'ROLLBACK-X')
        THROW 51999, 'ROLLBACK_TEST_FORZADO', 1;
END;
GO
